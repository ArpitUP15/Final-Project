"""Dataset strategy agent: deterministic guardrails with Ollama-assisted recommendations."""
from __future__ import annotations

from app.agents.evaluation_agent import is_regression_target
from app.agents.ollama_agent import ask_json

_ALLOWED_STRATEGIES = {
    "NoResampling", "ClassWeight", "SimilarityOverSampler", "RandomOverSampler",
    "RandomUnderSampler", "SMOTE", "SMOTENC", "TomekLinks", "SMOTETomek",
    "TextSynonymReplacement", "TextBackTranslation",
}


def _enrich_plan(plan: dict, analysis: dict) -> dict:
    """Let Ollama recommend only a validated strategy from an allow-list."""
    proposal = ask_json(
        "You are the strategy-planning agent in a tabular ML pipeline. Choose one strategy only from "
        "the provided allowed_strategies. Consider task, class imbalance, numeric/categorical columns, "
        "row count, missingness, and rare classes. Return JSON: {preferred_strategy: string, rationale: string, "
        "augmentation_cautions: [strings]}. Do not propose unsupported strategies or promise accuracy gains.",
        {
            "task": plan.get("task"),
            "class_count_values": sorted([int(v) for v in plan.get("class_counts", {}).values()], reverse=True),
            "number_of_classes": len(plan.get("class_counts", {})),
            "imbalance_ratio": plan.get("imbalance_ratio"), "is_imbalanced": plan.get("is_imbalanced"),
            "numeric_features": plan.get("numeric_features", [])[:40],
            "categorical_features": plan.get("categorical_features", [])[:40],
            "text_features": plan.get("text_features", [])[:20],
            "shape": analysis.get("shape", {}), "missing_rate": analysis.get("missing_values", {}).get("missing_rate", 0),
            "allowed_strategies": sorted(_ALLOWED_STRATEGIES),
            "rule_based_initial_strategy": plan.get("strategy"),
        }, num_predict=240,
    )
    if proposal:
        preferred = str(proposal.get("preferred_strategy", ""))
        if preferred in _ALLOWED_STRATEGIES:
            # Keep regression deterministic until a target-aware synthesizer exists.
            if plan.get("task") != "regression":
                if plan.get("text_features") and preferred not in {"TextSynonymReplacement", "TextBackTranslation"}:
                    # Preserve a text-compatible strategy when natural-language columns were detected.
                    pass
                else:
                    plan["strategy"] = preferred
            plan["llm_preferred_strategy"] = preferred
        plan["llm_rationale"] = str(proposal.get("rationale", ""))[:1200]
        cautions = proposal.get("augmentation_cautions", [])
        plan["llm_augmentation_cautions"] = [str(x)[:240] for x in cautions[:6]] if isinstance(cautions, list) else []
        plan["llm_status"] = "used"
    else:
        plan["llm_rationale"] = "Ollama unavailable/disabled; deterministic strategy retained."
        plan["llm_augmentation_cautions"] = []
        plan["llm_status"] = "fallback"
    return plan


def choose_strategy(df, target_column, analysis):
    y = df[target_column]
    counts = y.value_counts(dropna=False)
    if y.isna().any():
        raise ValueError("Target contains missing values. Remove or fix those rows first.")
    if y.nunique() < 2:
        raise ValueError("Target column must contain at least two classes.")
    if len(df) < 20:
        raise ValueError("At least 20 rows are needed for this initial evaluation.")
    numeric = analysis["column_types"]["numeric"]
    categorical = [c for c in df.columns if c not in numeric and c != target_column]
    from app.agents.execution_agent import _text_columns
    text_columns = _text_columns(df, target_column)
    if is_regression_target(df, target_column):
        plan = {
            "task": "regression", "target_column": target_column, "strategy": "NoResampling",
            "imbalance_ratio": None, "is_imbalanced": False, "class_counts": {},
            "categorical_features": list(map(str, categorical)),
            "numeric_features": list(map(str, [c for c in numeric if c != target_column])),
            "reason": "Numeric target has many distinct values; use regression metrics (MAE/RMSE/R²). "
                      "No synthetic regression rows are generated by the current target-aware augmentation methods.",
            "llm_rationale": None,
        }
        return _enrich_plan(plan, analysis)

    ratio = float(counts.max() / counts.min()) if counts.min() else None
    is_imbalanced = bool(ratio and ratio >= 1.5)
    method = ("TextSynonymReplacement" if text_columns and __import__("app.agents.ollama_agent", fromlist=["llm_enabled"]).llm_enabled()
              else ("ClassWeight" if is_imbalanced else "NoResampling"))
    reason = (
        "Class imbalance detected; compare class-weighted learning and leakage-safe resampling candidates."
        if is_imbalanced else
        "Class distribution is reasonably balanced; preserve the original distribution unless validation supports another method."
    )
    plan = {
        "task": "classification", "target_column": target_column, "strategy": method,
        "imbalance_ratio": round(ratio, 3) if ratio else None, "is_imbalanced": is_imbalanced,
        "class_counts": {str(k): int(v) for k, v in counts.items()},
        "categorical_features": list(map(str, categorical)),
        "text_features": list(map(str, text_columns)),
        "numeric_features": list(map(str, [c for c in numeric if c != target_column])),
        "reason": ("Natural-language feature(s) detected; use Ollama text augmentation before evaluating the candidate." if text_columns and method == "TextSynonymReplacement" else reason), "llm_rationale": None,
    }
    return _enrich_plan(plan, analysis)
